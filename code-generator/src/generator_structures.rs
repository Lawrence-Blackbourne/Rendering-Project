/// This macro will generate an enum which implements `GeneratedEnum`.
/// It will also implement `TryFrom<&str>`.
/// The enum will automatically have `#[non_exhaustive]` and
/// `#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]`, but other attributes and doc comments can be
/// added.
/// These other attributes and doc comments will be passed along to the ATTRIBUTES section, to be
/// used on the final enum in the generated code.
/// Similarly, doc comments and attributes can be added to each element, which will go to that
/// elements stored text, to be used on the final enum in the generated code.
/// The struct generated in place will have pub(super) and the one generated later will have the
/// visibility given for its elements.
/// todo FIX COMMENTS
/// TODO FIX FORMATTING
///
/// TODO take comments on data struct and pass it to the functions on xml enum
/// Have some kind of with data option on create_generator to allow us to pass an array of
/// `(ImageFormat, ImageFormatDetails)` when generating the final code which will then add functions
/// to get that data from the ImageFormat.
/// Move this all into one create_generator! function that can then also generate one big
/// generate_text function, which would take the above array
macro_rules! create_generator {
    // Internal helper branches.
    () => {};

    (@replace $old:tt, $new:tt) => {$new};

    (@format_attribute doc = $text:expr) => {concat!("///", $text)};
    (@format_attribute $other:meta) => {stringify!(#[$other])};

    (@enum_to_constant $name:ident, $element:ident) => {
        crate::generator_structures::Constant::Value(
            String::from(format!("{}::{}", stringify!($name), stringify!($element)))
        )
    };

    (@enum_to_constant $name:ident, $element:ident, $variable:ident) => {
        crate::generator_structures::Constant::List(crate::generator_structures::ConstantList {
            name: String::from(format!("{}::{}", stringify!($name), stringify!($element))),
            bracket: crate::generator_structures::ConstantBracket::Parenthesis,
            items: vec![$variable.to_constant()],
        }),
    };


    (@generate_text_implementation $name:ident, $type:ident $(,)?) => {
        impl $name {
            pub fn generate_text() -> String {
                format!(
                    "{}pub {} {} {{\n\
                    {}\n\
                    }}",
                    Self::ATTRIBUTES,
                    stringify!($type),
                    Self::NAME,
                    Self::ELEMENTS
                        .into_iter()
                        .map(|element| format!(
                            "{},", Self::generate_element_text(&element)
                        ))
                        .collect::<Vec<_>>()
                        .join("\n"),
                )
            }
        }
    };

    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
    ) => {
        #[derive(Debug)]
        pub struct GenerationData {
            $(pub $identifiers: Vec<($xml_enum_type, $getter_type)>,)*
        }

        impl GenerationData {
            pub fn new() -> GenerationData {
                GenerationData {
                    $($identifiers: Vec::new(),)*
                }
            }
        }

        pub fn generate_text(data: GenerationData) -> String {
            let mut result = String::from("///This file is automatically generated by xml-parser");
            $(result.push_str(&format!("\n\n{}", $names::generate_text()));)*
            $(result.push_str(&format!("\n\n{}", $getter_type::generate_text(data.$identifiers)));)*
            $(result.push_str(
                &format!("\n\nimpl {} {}", stringify!($types), stringify!($blocks))
            );)*
            result
        }
    };

    // The XML enum branch.
    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
        $(#[$($attribute:tt)*])*
        xml enum $name:ident {
            $(
                $(#[$($element_attribute:tt)*])*
                $element:ident $(: $xml_name:literal)?
            ),*
            $(,)?
        }
        $($tail:tt)*

    ) => {
        $(#[$($attribute)*])*
        #[non_exhaustive]
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum $name {
            $(
                $(#[$($element_attribute)*])*
                $element,
            )*
        }

        impl $name {
            const ATTRIBUTES: &'static str = concat!(
                $(create_generator!(@format_attribute $($attribute)*), "\n",)*
                "#[non_exhaustive]\n",
                "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n",
            );

            const NAME: &'static str = stringify!($name);

            const ELEMENTS: &'static [&str] = &[
                $(stringify!($element)),*
            ];

            fn generate_element_text(element: &str) -> &'static str {
                match element {
                    $(
                        stringify!($element) => concat!(
                            $("    ", create_generator!(
                                @format_attribute $($element_attribute)*
                            ), "\n",)*
                            "    ", stringify!($element)
                        ),
                    )*
                    _ => panic!("Unknown element"),
                }
            }
        }

        create_generator!(@generate_text_implementation $name, enum);

        impl TryFrom<&str> for $name {
            type Error = String;

            fn try_from(value: &str) -> Result<Self, Self::Error> {
                match value {
                    $($($xml_name => Ok($name::$element),)*)*
                    other => Err(
                        String::from(concat!("invalid ", stringify!($name), " value: ")) + other
                    ),
                }
            }
        }

        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                match self {$(
                    $name::$element => write!(f, "{}", stringify!($element)),
                )*}
            }
        }

        impl ToConstant for $name {
            fn to_constant(self, _: usize) -> crate::generator_structures::Constant {
                match self {$(
                    $name::$element => create_generator!(@enum_to_constant $name, $element),
                )*}
            }
        }

        create_generator!(@munch
            [names: $($names)* $name],
            [getters: $($getter_type, $xml_enum_type, $identifiers)*],
            [impls: $($types, $blocks)*],
            $($tail)*
        );
    };

    // The data struct branch
    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
        data struct $name:ident for $enum_name:ident as $identifier:ident {
            $(
                $(#[$($element_attribute:tt)*])*
                $element_name:ident: $type:ty
            ),*
            $(,)?
        }
        $($tail:tt)*
    ) => {
        #[derive(Debug)]
        pub struct $name {
            $(
                $(#[$($element_attribute)*])*
                pub $element_name: $type,
            )*
        }

        impl $name {
            pub fn generate_text(data: Vec<($enum_name, $name)>) -> String {
                //TODO check unique data entry present for all variants

                $(
                    let mut $element_name = format!(
                        "\n    fn {}(&self) -> {} {{\n        match self {{\n",
                        stringify!($element_name),
                        stringify!($type),
                    );
                )*

                for (variant, item) in data {
                    $($element_name.push_str(
                        &format!(
                            "            {}::{} => {},\n",
                            stringify!($enum_name),
                            variant,
                            item.$element_name.to_constant(4),
                        )
                    );)*
                }

                $(
                    $element_name += "        }\n    }\n    ";
                )*

                let mut result = format!("impl {} {{", stringify!($enum_name));
                $(result.push_str(&format!("{}", $element_name));)*
                result.push_str("}");
                result
            }
        }
        create_generator!(@munch
            [names: $($names)*],
            [getters: $($getter_type, $xml_enum_type, $identifiers)*
                $name, $enum_name, $identifier],
            [impls: $($types, $blocks)*],
            $($tail)*
        );
    };

    // The enum branch
    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
        $(#[$($attribute:tt)*])*
        enum $name:ident {
            $(
                $(#[$($element_attribute:tt)*])*
                $element:ident$(($type:ty))?
            ),*
            $(,)?
        }
        $($tail:tt)*
    ) => {
        $(#[$($attribute)*])*
        pub enum $name {
            $(
                $(#[$($element_attribute)*])*
                $element$(($type))*,
            )*
        }

        impl $name {
            const ATTRIBUTES: &'static str = concat!(
                $(create_generator!(@format_attribute $($attribute)*), "\n",)*
            );

            const NAME: &'static str = stringify!($name);

            const ELEMENTS: &'static [&str] = &[
                $(stringify!($element)),*
            ];

            fn generate_element_text(element: &str) -> &'static str {
                match element {
                    $(
                        stringify!($element) => concat!(
                            $("    ", create_generator!(
                                @format_attribute $($element_attribute)*
                            ), "\n",)*
                            "    ", stringify!($element$(($type))*)
                        ),
                    )*
                    _ => panic!("Unknown element"),
                }
            }
        }

        create_generator!(@generate_text_implementation $name, enum);

        impl ToConstant for $name {
            fn to_constant(self, indent_levels: usize) -> Constant {
                match self {
                    $(
                        $name::$element$(
                           (create_generator!(@replace $type, val))
                        )* => create_generator!(
                            @enum_to_constant
                            $name,
                            $element
                            $(, create_generator!(@replace $type, val))*
                        ),
                    )*
                }
            }
        }

        create_generator!(@munch
            [names: $($names)* $name],
            [getters: $($getter_type, $xml_enum_type, $identifiers)*],
            [impls: $($types, $blocks)*],
            $($tail)*
        );
    };

    // The struct branch.
    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
        $(#[$($attribute:tt)*])*
        struct $name:ident {
            $(
                $(#[$($element_attribute:tt)*])*
                $visibility:vis $element:ident: $type:ty
            ),*
            $(,)?
        }
        $($tail:tt)*
    ) => {
        $(#[$($attribute)*])*
        pub struct $name {
            $(
                $(#[$($element_attribute)*])*
                pub $element: $type,
            )*
        }

        impl $name {
            const ATTRIBUTES: &'static str = concat!(
                $(create_generator!(@format_attribute $($attribute)*), "\n",)*
            );

            const NAME: &'static str = stringify!($name);

            const ELEMENTS: &'static [&str] = &[
                $(stringify!($element)),*
            ];

            fn generate_element_text(element: &str) -> &str {
                match element {
                    $(stringify!($element) => {
                        if stringify!($visibility).is_empty() {
                            concat!(
                                concat!($("    ", create_generator!(
                                    @format_attribute $($element_attribute)*), "\n",
                                )*),
                                "    ", stringify!($element), ": ", stringify!($type),
                            )
                        } else {
                            concat!(
                                concat!($("    ", create_generator!(
                                    @format_attribute $($element_attribute)*), "\n",
                                )*),
                                "    ", stringify!($visibility), ' ', stringify!($element),
                                ": ", stringify!($type),
                            )
                        }
                    },)*
                    _ => panic!("Unknown element"),
                }
            }
        }

        create_generator!(@generate_text_implementation $name, struct);

        impl ToConstant for $name {
            fn to_constant(self, indent_levels: usize) -> String {
                let mut result = format!("{} {{\n", stringify!($name));
                $(result.push_str(&format!(
                    "    {}: {},",
                    stringify!($element),
                    self.$element.to_constant(indent_levels + 1),
                ));)*
                format!("{result}\n}}")
            }
        }

        create_generator!(@munch
            [names: $($names)* $name],
            [getters: $($getter_type, $xml_enum_type, $identifiers)*],
            [impls: $($types, $blocks)*],
            $($tail)*
        );
    };

    // The impl block branch
    (@munch
        [names: $($names:ident)*],
        [getters: $($getter_type:ident, $xml_enum_type:ident, $identifiers:ident)*],
        [impls: $($types:ty, $blocks:tt)*],
        impl $type:ident $block:tt
        $($tail:tt)*
    ) => {
        impl $type $block
        create_generator!(@munch
            [names: $($names)*],
            [getters: $($getter_type, $xml_enum_type, $identifiers)*],
            [impls: $($types, $blocks)* $type, $block],
            $($tail)*
        );
    };

    (
        $($tail:tt)*
    ) => {
        create_generator!(@munch
            [names: ],
            [getters: ],
            [impls: ],
            $($tail)*
        );
    };
}

pub(crate) use create_generator;